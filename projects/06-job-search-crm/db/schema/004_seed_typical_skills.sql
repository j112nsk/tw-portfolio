-- =====================================================================
-- 004_seed_typical_skills.sql
-- Job Search CRM: типовой набор навыков в справочник `skills`.
--
-- Зачем: в пустой базе справочник пуст, и подсказки при вводе навыков не работают.
-- После этой миграции в интерфейсе сразу есть из чего выбирать. Значения не привязаны
-- к направлению: справочник общий, а разделение SA/BA и TW — в отчёте Q6 (пробелы).
--
-- Миграция идемпотентна: где навык уже есть (без учёта регистра), повторно не вставляется.
-- Проверка на регистр — через lower(name); на уникальный индекс skills_name_ci_uk.
-- =====================================================================

insert into skills (name)
select v.name
  from (values
        -- Общие
        ('SQL'), ('Git'), ('Jira'), ('Confluence'), ('Postman'), ('Draw.io'),
        ('Figma'), ('Agile'), ('Scrum'), ('XML'), ('JSON'), ('CI/CD'),
        ('Тестирование'), ('Анализ требований'), ('Нефункциональные требования'),
        -- Системный / бизнес-аналитик
        ('BPMN'), ('UML'), ('Use Case'), ('User Story'),
        ('REST API'), ('SOAP'), ('OpenAPI'), ('Swagger/OpenAPI'),
        ('Kafka'), ('RabbitMQ'), ('Микросервисы'), ('Интеграции'),
        ('PostgreSQL'), ('Python'), ('ЭДО'),
        ('ER-диаграммы'), ('Sequence-диаграммы'),
        -- Технический писатель
        ('Markdown'), ('Docs-as-Code'), ('DITA'), ('Sphinx'), ('MkDocs'),
        ('Технический английский'), ('Руководство пользователя'),
        ('API-документация'), ('Стайлгайд')
       ) as v(name)
 where not exists (
        select 1 from skills s where lower(s.name) = lower(v.name)
       );